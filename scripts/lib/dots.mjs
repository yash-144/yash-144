// Returns { dots: [{c, r}], cols } where c/r are integer grid coordinates.
// `gap` is the number of unlit columns between glyphs.
export function dotText(str, gap = 1) {
  const dots = [];
  let col = 0;
  const chars = [...str.toUpperCase()];
  chars.forEach((ch, i) => {
    const g = G[ch] || G['?'];
    const w = g[0].length;
    for (let r = 0; r < 7; r++) for (let c = 0; c < w; c++) if (g[r][c] === '#') dots.push({ c: col + c, r, ch: i });
    col += w + (i < chars.length - 1 ? gap : 0);
  });
  return { dots, cols: col };
}

export const dotWidth = (str, pitch, gap = 1) => (dotText(str, gap).cols - 1) * pitch;
